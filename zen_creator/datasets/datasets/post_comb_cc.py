"""Dataset for post-combustion carbon-capture retrofit parametrization
(ceramic_post_comb, glass_post_comb), sourced from the Danish Energy Agency
"Technology Data for Carbon Capture, Transport and Storage" catalogue
(input_data/CCS/).

There is no ceramic- or glass-specific post-combustion capture sheet in the
DEA catalogue, and the capture-plant physics (heat/electricity duty, capex,
opex per tCO2 captured) are properties of the generic amine-capture unit
rather than of the industry it is bolted onto. Sheet "401.c Post comb -
Cement kiln" is therefore reused as-is for both sectors, the same way the
cement sector's own `cement_post_comb` retrofit (present in the external
base dataset, not generated by this repo) was built from this exact sheet
— confirmed by an exact match between this sheet's 2020 "Est" values and
`cement_post_comb`'s `attributes.json` (0.833 MWh/tCO2 heat input, 0.025
MWh/tCO2 electricity input, 1.65 MWh/tCO2 heat output, 90% capture rate,
25 yr lifetime). See ASSUMPTIONS.md ("Ceramic and glass post-combustion
carbon capture") for the full derivation.

Unlike `DeaIndustrialHeatDataset` (JRC-EU-TIMES-adjacent boilers/heat pumps),
no price-year deflator is applied here, following that same dataset's own
convention of using DEA figures as-is (only unit conversion) — this is a
deliberate choice not to reproduce `cement_post_comb`'s own capex/opex
figures, which carry a small (~0.25%) scaling factor that could not be
traced to anything in this repo.
"""

from __future__ import annotations

import functools
from pathlib import Path
from typing import TYPE_CHECKING

import pandas as pd

if TYPE_CHECKING:
    from zen_creator.elements.element import Element

from zen_creator.datasets.datasets._industry_heat_utils import INPUT_DATA
from zen_creator.datasets.datasets.dataset import Dataset
from zen_creator.datasets.datasets.dea_industrial_heat import (
    MODEL_FIRST_YEAR,
    MODEL_LAST_YEAR,
    _interpolate_to_model_years,
    _is_constant,
)
from zen_creator.datasets.datasets.metadata import MetaData, SourceInformation
from zen_creator.datasets.datasets.process_parametrization import ProcessParametrizationDataset
from zen_creator.utils.attribute import Attribute

_CCS_XLSX = INPUT_DATA / "CCS" / "technology_data_for_carbon_capture_transport_storage.xlsx"
_CCS_SHEET = "alldata_flat"
_WS = "401.c Post comb - Cement kiln"

_HEAT_INPUT_LABEL = "C1] Heat  input [MWh/tCO2] (CO2 output)"
_HEAT_OUTPUT_LABEL = "C1] Heat out [MWh/tCO2] (CO2 output) "
_ELECTRICITY_LABEL = "C2] Eletricity input [MWh/tCO2] (CO2 output)"
_CAPTURE_RATE_LABEL = "A3] CO2 capture rate, net [%]"
_CAPEX_LABEL = "Specific investment [mill €/[tCO2/hour]] (CO2 output)"
_OPEX_FIXED_LABEL = "Fixed O&M [mill €/[tCO2/hour]] (CO2 output)"
_OPEX_VARIABLE_LABEL = "Variable O&M [€/tCO2] (CO2 output)"
_LIFETIME_LABEL = "Technical lifetime [years]"

# EUR million per (tCO2/hour) -> EUR per (tCO2eq/hour)
_MILL_EUR_PER_TCO2H_TO_EUR_PER_TCO2EQH = 1e6

# Retrofit-specific technology-instance parameters that aren't in the DEA
# sheet in a directly usable form: carried forward unchanged from
# cement_post_comb, since it's the same underlying DEA "typical plant"
# capture-unit spec, just bolted onto a different base technology. See
# ASSUMPTIONS.md.
CAPACITY_ADDITION_UNBOUNDED = 0.0114155
MAX_DIFFUSION_RATE = 0.13

# Fuels supplying the capture unit's own auxiliary heat demand (natural_gas +
# hard_coal only, no oil/biomass/electricity for the heat share — see
# ASSUMPTIONS.md), split proportionally to each sector's own existing
# natural_gas:hard_coal ratio.
_FUEL_SPLIT_CARRIERS = ("natural_gas", "hard_coal")


@functools.lru_cache(maxsize=1)
def _load_alldata_flat() -> pd.DataFrame:
    return pd.read_excel(_CCS_XLSX, sheet_name=_CCS_SHEET)


def _year_values(label: str) -> dict[int, float]:
    """DEA {year: value} pairs for the cement-kiln post-comb sheet, central ("Est") estimate."""
    df = _load_alldata_flat()
    rows = df[(df["ws"] == _WS) & (df["par"] == label) & (df["est"] == "Est")]
    if rows.empty:
        raise ValueError(f"No DEA data found for ws={_WS!r}, par={label!r}")
    return dict(zip(rows["year"], rows["val"]))


def _value_2020(label: str) -> float:
    return _year_values(label)[2020]


class PostCombCCDataset(Dataset[pd.DataFrame]):

    name = "post_comb_cc"

    def __init__(self, source_path: Path | str | None = None):
        super().__init__(source_path=source_path)

    def _set_metadata(self) -> MetaData:
        return MetaData(
            name=self.name,
            title="Technology Data for Carbon Capture, Transport and Storage",
            author=["Danish Energy Agency"],
            publication="Technology Data for Carbon Capture, Transport and Storage",
            publication_year=2023,
        )

    def _set_path(self) -> Path | None:
        return _CCS_XLSX

    def _set_data(self) -> pd.DataFrame:
        return pd.DataFrame()

    def _source_info(self, description: str) -> SourceInformation:
        return SourceInformation(description=description, metadata=self.metadata)

    def _ng_coal_split(self, sector: str) -> dict[str, float]:
        """Renormalized natural_gas/hard_coal shares of the sector's own fuel mix."""
        shares = ProcessParametrizationDataset()._fuel_shares[sector]
        subset = {c: shares[c] for c in _FUEL_SPLIT_CARRIERS if c in shares}
        total = sum(subset.values())
        return {c: v / total for c, v in subset.items()}

    def get_conversion_factor(self, element: Element, sector: str) -> Attribute:
        heat_input = _value_2020(_HEAT_INPUT_LABEL)
        heat_output = _value_2020(_HEAT_OUTPUT_LABEL)
        electricity = _value_2020(_ELECTRICITY_LABEL)
        split = self._ng_coal_split(sector)

        entries = [
            {carrier: {"default_value": round(heat_input * share, 12), "unit": "GW/(kilotCO2eq/hour)"}}
            for carrier, share in split.items()
        ]
        entries.append({"electricity": {"default_value": electricity, "unit": "GW/(kilotCO2eq/hour)"}})
        entries.append({"district_heat": {"default_value": heat_output, "unit": "GW/(kilotCO2eq/hour)"}})

        attr = Attribute("conversion_factor", element=element)
        attr.set_data(
            default_value=entries,
            source=self._source_info(
                f"Post-combustion CC conversion factors for {sector}_post_comb from DEA sheet "
                f"{_WS!r} (2020 Est): heat input {heat_input} MWh/tCO2 split {split} between "
                f"natural_gas/hard_coal, electricity {electricity} MWh/tCO2, heat output "
                f"{heat_output} MWh/tCO2 as district_heat."
            ),
        )
        return attr

    def get_capex_specific_conversion(self, element: Element, sector: str) -> Attribute:
        year_values = {y: v * _MILL_EUR_PER_TCO2H_TO_EUR_PER_TCO2EQH for y, v in _year_values(_CAPEX_LABEL).items()}
        series = _interpolate_to_model_years(year_values)
        attr = Attribute("capex_specific_conversion", element=element)
        attr.set_data(
            default_value=float(series.loc[MODEL_FIRST_YEAR]), unit="Euro/(kilotCO2eq/hour)",
            df=None if _is_constant(series) else series.to_frame("capex_specific_conversion"),
            source=self._source_info(
                f"Specific investment for {sector}_post_comb from DEA sheet {_WS!r}, "
                f"interpolated over {MODEL_FIRST_YEAR}-{MODEL_LAST_YEAR}."
            ),
        )
        return attr

    def get_opex_specific_fixed(self, element: Element, sector: str) -> Attribute:
        year_values = {y: v * _MILL_EUR_PER_TCO2H_TO_EUR_PER_TCO2EQH for y, v in _year_values(_OPEX_FIXED_LABEL).items()}
        series = _interpolate_to_model_years(year_values)
        attr = Attribute("opex_specific_fixed", element=element)
        attr.set_data(
            default_value=float(series.loc[MODEL_FIRST_YEAR]), unit="Euro/(kilotCO2eq/hour)",
            df=None if _is_constant(series) else series.to_frame("opex_specific_fixed"),
            source=self._source_info(
                f"Fixed O&M for {sector}_post_comb from DEA sheet {_WS!r}, "
                f"interpolated over {MODEL_FIRST_YEAR}-{MODEL_LAST_YEAR}."
            ),
        )
        return attr

    def get_opex_specific_variable(self, element: Element, sector: str) -> Attribute:
        val = _value_2020(_OPEX_VARIABLE_LABEL)
        attr = Attribute("opex_specific_variable", element=element)
        attr.set_data(
            default_value=val, unit="Euro/tCO2eq",
            source=self._source_info(f"Variable O&M for {sector}_post_comb from DEA sheet {_WS!r} (2020 Est)."),
        )
        return attr

    def get_lifetime(self, element: Element, sector: str) -> Attribute:
        val = _value_2020(_LIFETIME_LABEL)
        attr = Attribute("lifetime", element=element)
        attr.set_data(
            default_value=float(val), unit="1",
            source=self._source_info(f"Technical lifetime for {sector}_post_comb from DEA sheet {_WS!r}."),
        )
        return attr

    def get_retrofit_flow_coupling_factor(self, element: Element, sector: str) -> Attribute:
        """coupling_factor = base tech's carbon_intensity_technology x DEA capture rate.

        Mirrors cement_post_comb exactly (0.54 x 0.90 = 0.486 t/tonproduct):
        captures the base production tech's own (process-only)
        carbon_intensity_technology attribute, not the additional combustion
        CO2 tracked separately via the fuel carriers it consumes. See
        ASSUMPTIONS.md for the caveat this implies.
        """
        base_intensity = ProcessParametrizationDataset().get_carbon_intensity_technology(element, sector).default_value
        capture_rate = _value_2020(_CAPTURE_RATE_LABEL) / 100.0
        factor = round(base_intensity * capture_rate / 1000.0, 12)  # ton/tonproduct -> kiloton/tonproduct
        attr = Attribute("retrofit_flow_coupling_factor", element=element)
        attr.set_data(
            default_value=factor, unit="kilotCO2eq/tonproduct",
            source=self._source_info(
                f"{sector}_post_comb retrofit_flow_coupling_factor = {sector}_production."
                f"carbon_intensity_technology ({base_intensity} ton/tonproduct) x DEA capture rate "
                f"({capture_rate:.0%}, sheet {_WS!r}, 2020 Est)."
            ),
        )
        attr.base_technology = f"{sector}_production"
        return attr

    def get_capacity_addition_unbounded(self, element: Element, sector: str) -> Attribute:
        attr = Attribute("capacity_addition_unbounded", element=element)
        attr.set_data(
            default_value=CAPACITY_ADDITION_UNBOUNDED, unit="kilotCO2eq/hour",
            source=self._source_info(
                f"{sector}_post_comb capacity_addition_unbounded carried forward unchanged from "
                "cement_post_comb (same underlying DEA 'typical plant' capture-unit spec)."
            ),
        )
        return attr

    def get_max_diffusion_rate(self, element: Element, sector: str) -> Attribute:
        attr = Attribute("max_diffusion_rate", element=element)
        attr.set_data(
            default_value=MAX_DIFFUSION_RATE, unit="1",
            source=self._source_info(
                f"{sector}_post_comb max_diffusion_rate carried forward unchanged from cement_post_comb."
            ),
        )
        return attr
